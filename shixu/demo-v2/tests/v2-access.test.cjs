test('Accounts inherit role permissions but store scope comes from the account',()=>{
 const s=D.initialState();
 a.deepEqual(D.allowedStores(s,'u-su'),['sh']);
 a.deepEqual(D.allowedStores(s,'u-chen'),['sh','sh-west']);
 a.equal(D.allowedStores(s,'u-zhou').length,4);
 a.ok(D.can(s,'u-gu','pos:use'));
 a.equal(D.can(s,'u-gu','store:stock'),false);
 a.equal(D.can(s,'u-gu','order:refund'),false);
 a.ok(D.can(s,'u-xu','dashboard:profit'));
 a.equal(D.can(s,'u-xu','product:edit'),false);
 a.throws(()=>D.requireStore(s,'u-su','bj'),/授权/);
 a.doesNotThrow(()=>D.requireStore(s,'u-chen','sh-west'));
 s.staff.find(u=>u.id==='u-gu').active=false;
 a.equal(D.can(s,'u-gu','pos:use'),false);
 a.deepEqual(D.allowedStores(s,'u-gu'),[]);
});
test('Account and role assignment cannot escalate beyond the operator, and builtins are protected',()=>{
 const s=D.initialState();
 s.roles.push({id:'r-hr',name:'门店HR',scope:'STORES',perms:['rbac:view','rbac:edit','pos:use']});
 s.staff.find(x=>x.id==='u-chen').roleIds.push('r-hr');
 a.throws(()=>D.saveStaff(s,'u-chen',{name:'越权同事',username:'13900000000',roleIds:['r-super'],stores:['sh']}),/超出/);
 a.throws(()=>D.saveStaff(s,'u-chen',{name:'跨店同事',username:'13900000000',roleIds:['r-staff'],stores:['bj']}),/看不到/);
 const u=D.saveStaff(s,'u-chen',{name:'新同事',username:'13900000000',roleIds:['r-staff'],stores:['sh']});
 a.ok(D.can(s,u.id,'pos:use'));
 a.equal(D.can(s,u.id,'rbac:edit'),false);
 a.throws(()=>D.saveStaff(s,'u-lin',{id:'u-lin',name:'林知秋',username:'13800000001',roleIds:['r-super'],stores:['*'],active:false}),/不能停用/);
 a.throws(()=>D.saveRole(s,'u-lin',{id:'r-super',name:'超级管理员',scope:'ALL',perms:['*']}),/内置/);
 const copy=D.cloneRole(s,'u-lin','r-staff','试用店员');
 a.equal(copy.builtin,false);a.equal(copy.perms.length,D.ROLE_TEMPLATES.find(r=>r.id==='r-staff').perms.length);
 a.throws(()=>D.removeRole(s,'u-lin','r-super'),/内置/);
 D.removeRole(s,'u-lin',copy.id);
 a.equal(s.roles.some(r=>r.id===copy.id),false);
 const used=D.cloneRole(s,'u-lin','r-staff','临时角色');
 s.staff.find(x=>x.id==='u-gu').roleIds.push(used.id);
 a.throws(()=>D.removeRole(s,'u-lin',used.id),/账号/);
});
test('Refunds at or above the threshold wait for HQ approval, then execute once',()=>{
 const s=D.initialState(),o=retail(s,2),before=D.financeSummary(s);
 a.equal(o.total,2400);
 a.equal(D.refundNeedsApproval(s,'u-lin',o.total),false);
 const high=retail(s,5);a.equal(high.total,6000);a.equal(D.refundNeedsApproval(s,'u-lin',high.total),true);
 const res=D.requestRefund(s,'u-lin',high.id,[{index:0,qty:5}],'顾客改约',false);
 a.equal(res.mode,'approval');const ap=res.approval;
 a.equal(ap.status,'pending');a.equal(D.pendingRefund(s,high.id).id,ap.id);
 a.throws(()=>D.requestRefund(s,'u-lin',high.id,[{index:0,qty:5}],'重复',false),/审批/);
 a.throws(()=>D.decideApproval(s,'u-su',ap.id,'approve'),/权限|审批人/);
});
test('Approval approval writes a negative ledger once and marks the order refunded',()=>{
 const s=D.initialState(),o=retail(s,5),before=D.financeSummary(s);
 const ap=D.requestRefund(s,'u-lin',o.id,[{index:0,qty:5}],'顾客改约',false).approval;
 const done=D.decideApproval(s,'u-zhou',ap.id,'approve','同意');
 a.equal(done.status,'approved');a.match(done.resultNote,/已退款/);
 a.equal(o.status,'refunded');a.equal(D.pendingRefund(s,o.id),null);
 const after=D.financeSummary(s);
 a.equal(after.entries,before.entries+1);
 a.equal(after.refunds,before.refunds+6000);
 a.equal(after.net,before.net-6000);
 a.throws(()=>D.decideApproval(s,'u-zhou',ap.id,'approve'),/已结束/);
 a.equal(s.finance.filter(f=>f.orderId===o.id&&f.type==='REFUND').length,1);
});
test('Rejected approval leaves the order untouched and records the decision',()=>{
 const s=D.initialState(),o=retail(s,5),before=D.financeSummary(s);
 const ap=D.requestRefund(s,'u-lin',o.id,[{index:0,qty:5}],'顾客改约',false).approval;
 const done=D.decideApproval(s,'u-zhou',ap.id,'reject','金额需要店长复核');
 a.equal(done.status,'rejected');a.match(done.resultNote,/驳回/);
 a.equal(o.status,'awaiting');a.equal(o.refunded,0);
 a.equal(D.financeSummary(s).refunds,before.refunds);
 a.ok(done.nodes[0].decisions.some(d=>d.approverId==='u-zhou'));
});
