test('Approval visibility follows store scope, requester and finance access',()=>{
 const s=D.initialState();
 const fresh=D.placeOrder(s,{store:'sh',channel:'mini',type:'takeaway',owner:'customer',lines:[{id:'song-0',qty:3,temp:'热'}]});
 const ap=D.requestRefund(s,'u-gu',fresh.id,[{index:0,qty:3}],'顾客改约',false).approval;
 a.ok(D.visibleApprovals(s,'u-zhou').some(x=>x.id===ap.id));
 a.ok(D.visibleApprovals(s,'u-lin').some(x=>x.id===ap.id));
 a.ok(D.visibleApprovals(s,'u-gu').some(x=>x.id===ap.id));
 a.ok(D.visibleApprovals(s,'u-chen').some(x=>x.id===ap.id));
 a.ok(D.visibleApprovals(s,'u-su').some(x=>x.id===ap.id));
 a.ok(D.visibleApprovals(s,'u-xu').some(x=>x.id===ap.id));
 const bj=D.placeOrder(s,{store:'bj',channel:'mini',type:'takeaway',owner:'customer',lines:[{id:'song-0',qty:3,temp:'热'}]});
 const bjAp=D.requestRefund(s,'u-lin',bj.id,[{index:0,qty:3}],'北京门店',false).approval;
 a.equal(D.visibleApprovals(s,'u-gu').some(x=>x.id===bjAp.id),false);
 a.equal(D.visibleApprovals(s,'u-chen').some(x=>x.id===bjAp.id),false);
 a.equal(D.myApprovals(s,'u-zhou').some(x=>x.id===ap.id),true);
 a.equal(D.myApprovals(s,'u-gu').some(x=>x.id===ap.id),false);
 const brand=D.placeRetailOrder(s,{channel:'mini',owner:'customer',lines:[{id:'retail-0',qty:5}]});
 const retailAp=D.requestRefund(s,'u-lin',brand.id,[{index:0,qty:5}],'品牌零售',false).approval;
 a.equal(D.visibleApprovals(s,'u-gu').some(x=>x.id===retailAp.id),false);
 a.ok(D.visibleApprovals(s,'u-xu').some(x=>x.id===retailAp.id));
});
