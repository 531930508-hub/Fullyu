test('Finance summaries can be constrained to an account store scope',()=>{
 const s=D.initialState();
 const sh=D.placeOrder(s,{store:'sh',channel:'mini',type:'takeaway',owner:'customer',lines:[{id:'song-0',qty:1,temp:'热'}]});
 const bj=D.placeOrder(s,{store:'bj',channel:'mini',type:'takeaway',owner:'customer',lines:[{id:'song-0',qty:1,temp:'热'}]});
 const all=D.financeSummary(s),one=D.financeSummary(s,{storeIds:['sh']});
 a.equal(all.entries,2);a.equal(one.entries,1);a.equal(one.net,sh.total);a.equal(D.financeSummary(s,{storeId:'bj'}).net,bj.total);
 a.equal(D.financeSummary(s,{storeIds:['sh','bj']}).entries,2);
});
