-- ============================================================
-- 会员卡提前价改为「实时口径」
--
-- 背景：结算与会员中心现在都按当期配置（CRM 在线时以 CRM 下发为准）取折扣率，
--       c_customer_member_card.advance_rate 只作为配置缺失时的兜底快照。
--       因此卡配置里的条款文案不能再写「已生效权益期按开卡时快照执行」。
-- ============================================================

UPDATE `s_member_card_config`
SET `terms` = REPLACE(`terms`, '已生效权益期按开卡时快照执行', '有效期内按会员当期配置享受权益'),
    `update_time` = NOW()
WHERE `terms` LIKE '%已生效权益期按开卡时快照执行%';